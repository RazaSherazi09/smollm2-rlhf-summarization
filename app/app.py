import os
import streamlit as st
import torch
import torch.nn as nn
from transformers import AutoTokenizer, AutoModelForCausalLM
from huggingface_hub import snapshot_download

st.set_page_config(
    page_title="SmolLM2-135M RLHF Arena",
    page_icon="⚖️",
    layout="wide",
)

HF_REPO_ID = "razaasherazi/smollm2-135m-rlhf-checkpoints"

class RewardModel(nn.Module):
    """Reward Model using the SFT backbone with a scalar value head."""
    def __init__(self, base_causal_lm):
        super().__init__()
        self.transformer = base_causal_lm.model
        hidden_size = base_causal_lm.config.hidden_size
        self.v_head = nn.Linear(hidden_size, 1, bias=False)

    def forward(self, input_ids, attention_mask):
        outputs = self.transformer(input_ids=input_ids, attention_mask=attention_mask)
        last_indices = (attention_mask.sum(dim=1) - 1).clamp(min=0)
        batch_idx = torch.arange(input_ids.shape[0], device=input_ids.device)
        last_hidden = outputs.last_hidden_state[batch_idx, last_indices]
        return self.v_head(last_hidden).squeeze(-1)


def resolve_model_path(stage_subfolder):
    """Returns local path if available; otherwise fetches from Hugging Face Hub."""
    local_path = os.path.join("checkpoints", stage_subfolder)
    if os.path.exists(local_path) and os.listdir(local_path):
        return local_path
    
    downloaded_dir = snapshot_download(
        repo_id=HF_REPO_ID,
        allow_patterns=f"{stage_subfolder}/*",
    )
    return os.path.join(downloaded_dir, stage_subfolder)


@st.cache_resource(show_spinner=False)
def load_all_models():
    device = "cuda" if torch.cuda.is_available() else "cpu"
    tok = AutoTokenizer.from_pretrained("HuggingFaceTB/SmolLM2-135M")
    if tok.pad_token_id is None:
        tok.pad_token = tok.eos_token

    # 1. Load SFT
    sft_path = resolve_model_path("sft")
    sft_model = AutoModelForCausalLM.from_pretrained(sft_path, torch_dtype=torch.float32).to(device).eval()

    # 2. Load PPO
    ppo_path = resolve_model_path("ppo")
    ppo_model = AutoModelForCausalLM.from_pretrained(ppo_path, torch_dtype=torch.float32).to(device).eval()

    # 3. Load DPO
    dpo_path = resolve_model_path("dpo")
    dpo_model = AutoModelForCausalLM.from_pretrained(dpo_path, torch_dtype=torch.float32).to(device).eval()

    # 4. Load Reward Model (shares SFT backbone in memory to conserve RAM)
    rm_path = resolve_model_path("reward")
    rm_model = RewardModel(sft_model).to(device).eval()
    weights_file = os.path.join(rm_path, "reward_model.pt")
    if os.path.exists(weights_file):
        rm_model.load_state_dict(torch.load(weights_file, map_location=device, weights_only=True))

    return tok, sft_model, ppo_model, dpo_model, rm_model, device


def generate_summary(model, tokenizer, prompt_text, device, max_new_tokens=48):
    inputs = tokenizer(prompt_text, return_tensors="pt", truncation=True, max_length=448).to(device)
    prompt_len = inputs["input_ids"].shape[1]
    with torch.no_grad():
        out = model.generate(
            **inputs,
            max_new_tokens=max_new_tokens,
            do_sample=False,
            pad_token_id=tokenizer.pad_token_id,
            eos_token_id=tokenizer.eos_token_id,
        )
    gen_tokens = out[0, prompt_len:]
    raw_text = tokenizer.decode(gen_tokens, skip_special_tokens=False)
    if "<|endoftext|>" in raw_text:
        raw_text = raw_text.split("<|endoftext|>")[0]
    return raw_text.strip()


def compute_reward_score(reward_model, tokenizer, prompt_text, summary_text, device):
    full_text = prompt_text.strip() + " " + summary_text.strip() + "<|endoftext|>"
    inputs = tokenizer(full_text, return_tensors="pt", truncation=True, max_length=512).to(device)
    with torch.no_grad():
        score = reward_model(inputs["input_ids"], inputs["attention_mask"]).item()
    return round(score, 3)


# --- Streamlit UI Layout ---
st.title("⚖️ SmolLM2-135M RLHF & DPO Summarization Arena")
st.markdown(
    "Compare summaries generated by **SFT** (Stage 1), **PPO** (Stage 3), and **DPO** (Stage 4) "
    "alongside their scalar scores from the trained **Reward Model** ($r_\\phi$)."
)

with st.spinner("Loading model weights..."):
    tok, sft_model, ppo_model, dpo_model, rm_model, device = load_all_models()

default_sample = (
    "I have been working at my current software company for two years as a junior developer. "
    "I recently received a job offer from another firm that pays 25% more salary, but requires "
    "full in-office attendance with a 45-minute commute each way. My current job is 100% remote, "
    "and I value my flexibility and work-life balance greatly. I have to make a final decision by Monday."
)

user_post = st.text_area(
    "Paste Reddit Post Content:",
    value=default_sample,
    height=140,
    help="Paste post text here. '\\nTL;DR:' is automatically appended to prompt the models.",
)

if st.button("Generate & Compare Summaries", type="primary", use_container_width=True):
    formatted_prompt = user_post.strip() + "\nTL;DR:"

    with st.spinner("Generating summaries across all models..."):
        sft_summary = generate_summary(sft_model, tok, formatted_prompt, device)
        ppo_summary = generate_summary(ppo_model, tok, formatted_prompt, device)
        dpo_summary = generate_summary(dpo_model, tok, formatted_prompt, device)

        sft_score = compute_reward_score(rm_model, tok, formatted_prompt, sft_summary, device)
        ppo_score = compute_reward_score(rm_model, tok, formatted_prompt, ppo_summary, device)
        dpo_score = compute_reward_score(rm_model, tok, formatted_prompt, dpo_summary, device)

    col1, col2, col3 = st.columns(3)

    with col1:
        st.subheader("Stage 1: SFT")
        st.info(sft_summary)
        st.metric("Reward Score ($r_\\phi$)", f"{sft_score:+.3f}")

    with col2:
        st.subheader("Stage 3: PPO")
        st.success(ppo_summary)
        st.metric("Reward Score ($r_\\phi$)", f"{ppo_score:+.3f}", delta=round(ppo_score - sft_score, 3))

    with col3:
        st.subheader("Stage 4: DPO")
        st.success(dpo_summary)
        st.metric("Reward Score ($r_\\phi$)", f"{dpo_score:+.3f}", delta=round(dpo_score - sft_score, 3))